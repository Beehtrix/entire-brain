func publicationCandidate(t *testing.T) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "candidate.sqlite")
	db, err := sql.Open(sqlitedriver.Name, path)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	if _, err := db.Exec(`CREATE TABLE evidence (value TEXT); INSERT INTO evidence VALUES ('committed')`); err != nil {
		t.Fatal(err)
	}
	if err := db.Close(); err != nil {
		t.Fatal(err)
	}
	return path
}

// The fixture decoder accepts the current marker generated by publication.
// CLI integration tests exercise the authoritative privacy/version classifier.
func decodePublicationFixture(data []byte) (patterns.CorpusPublication, error) {
	var marker patterns.CorpusPublication
	err := json.Unmarshal(data, &marker)
	return marker, err
}

func TestCorpusPublicationRecoversCandidateAndRenamedDatabase(t *testing.T) {
	for _, boundary := range []string{"after_marker_create", "after_main_rename"} {
		t.Run(boundary, func(t *testing.T) {
			root := t.TempDir()
			candidate := publicationCandidate(t)
			crash := errors.New("publication interrupted")
			original := patterns.CorpusPublishBoundary
			t.Cleanup(func() { patterns.CorpusPublishBoundary = original })
			patterns.CorpusPublishBoundary = func(at string) error {
				if at == boundary {
					return crash
				}
				return nil
			}
			err := brainstore.WithBrainWriteLock(root, func() error {
				return patterns.PublishCorpusLocked(root, candidate, decodePublicationFixture)
			})
			if !errors.Is(err, crash) {
				t.Fatalf("publication error = %v, want crash", err)
			}
			markerPath := filepath.Join(root, patterns.CorpusPublicationMarkerPath)
			if _, err := os.Stat(markerPath); err != nil {
				t.Fatalf("interruption lost recovery marker: %v", err)
			}
			patterns.CorpusPublishBoundary = original
			if err := brainstore.WithBrainWriteLock(root, func() error {
				return patterns.RecoverCorpusPublicationLocked(root, decodePublicationFixture)
			}); err != nil {
				t.Fatal(err)
			}
			if _, err := os.Stat(markerPath); !os.IsNotExist(err) {
				t.Fatalf("recovery left marker: %v", err)
			}
			stage, cleanup, err := patterns.PrepareCorpusStaging(root)
			if err != nil {
				t.Fatal(err)
			}
			defer cleanup()
			db, err := sql.Open(sqlitedriver.Name, brainstore.SQLiteReadOnlyDSN(stage))
			if err != nil {
				t.Fatal(err)
			}
			defer db.Close()
			var value string
			if err := db.QueryRow(`SELECT value FROM evidence`).Scan(&value); err != nil || value != "committed" {
				t.Fatalf("recovered value=%q err=%v", value, err)
			}
		})
	}
}

func TestCorpusPublicationPreservesRejectedMarkerAndCandidate(t *testing.T) {
	root := t.TempDir()
	candidate := publicationCandidate(t)
	crash := errors.New("publication interrupted")
	original := patterns.CorpusPublishBoundary
	t.Cleanup(func() { patterns.CorpusPublishBoundary = original })
	patterns.CorpusPublishBoundary = func(at string) error {
		if at == "after_marker_create" {
			return crash
		}
		return nil
	}
	if err := brainstore.WithBrainWriteLock(root, func() error {
		return patterns.PublishCorpusLocked(root, candidate, decodePublicationFixture)
	}); !errors.Is(err, crash) {
		t.Fatalf("publication error = %v, want crash", err)
	}
	patterns.CorpusPublishBoundary = original
	markerPath := filepath.Join(root, patterns.CorpusPublicationMarkerPath)
	markerBytes, err := os.ReadFile(markerPath)
	if err != nil {
		t.Fatal(err)
	}
	marker, err := decodePublicationFixture(markerBytes)
	if err != nil {
		t.Fatal(err)
	}
	candidatePath := filepath.Join(root, "patterns", marker.Candidate)
	candidateBytes, err := os.ReadFile(candidatePath)
	if err != nil {
		t.Fatal(err)
	}
	rejected := errors.New("marker rejected by caller's version policy")
	calls := 0
	decode := func(data []byte) (patterns.CorpusPublication, error) {
		calls++
		if !bytes.Equal(data, markerBytes) {
			t.Fatal("decoder did not receive the pinned marker bytes")
		}
		return patterns.CorpusPublication{}, rejected
	}
	for _, operation := range []func() error{
		func() error { return patterns.RecoverCorpusPublicationLocked(root, decode) },
		func() error { return patterns.PublishCorpusLocked(root, candidate, decode) },
	} {
		if err := brainstore.WithBrainWriteLock(root, operation); err != rejected {
			t.Fatalf("decoder error identity lost: %v", err)
		}
	}
	if calls != 2 {
		t.Fatalf("decoder calls=%d, want both recovery and publication", calls)
	}
	for path, want := range map[string][]byte{markerPath: markerBytes, candidatePath: candidateBytes} {
		got, err := os.ReadFile(path)
		if err != nil || !bytes.Equal(got, want) {
			t.Fatalf("rejected state changed at %s: %v", path, err)
		}
	}
	if _, err := os.Stat(filepath.Join(root, patterns.CorpusPath)); !os.IsNotExist(err) {
		t.Fatalf("rejected candidate became live: %v", err)
	}
}
